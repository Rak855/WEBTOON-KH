export function t(pair: { kh: string; en: string }, lang: Language): string {
  return pair[lang];
}

export function formatCompactNumber(value: number, lang: Language): string {
  if (value >= 1_000_000) {
    const m = (value / 1_000_000).toFixed(1).replace(/\.0$/, '');
    return lang === 'kh' ? `${m} លាន` : `${m}M`;
  }
  if (value >= 1_000) {
    const k = (value / 1_000).toFixed(1).replace(/\.0$/, '');
    return lang === 'kh' ? `${k} ពាន់` : `${k}K`;
  }
  return value.toLocaleString();
}
